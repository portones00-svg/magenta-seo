function requireAuth(rutasPublicas) {
  return (req, res, next) => {
    if (rutasPublicas.some(ruta => req.path === ruta || req.path.startsWith(ruta))) {
      return next();
    }
    if (req.session && req.session.autenticado) {
      return next();
    }
    res.redirect('/login');
  };
}

